"""Generate the projects the benchmark runs: pipelines of trivial stages in several shapes.

Shapes (every stage is its own module-level function, so an edit changes one stage):
  chain-N    s00000(in_00000) -> s00001 -> ... -> s{N-1}
  fan-N      s00000(in_src); s_i(s00000, in_i) for 0 < i < N-1; s{N-1}([s_1 .. s_{N-2}])
  diamond-N  W = ceil(sqrt(N)) wide layers; layer 0 node j reads in_j;
             node (k, j) depends on (k-1, j) and (k-1, (j+1) % W)
  multi      pipeline `prep` (a chain of 5 stages) feeds pipelines fam_00, fam_01 and fam_02,
             each a stage `b` and 4 tasks t00..t03 of 5 chained stages

Each stage folds its inputs into its output, so a changed input reruns its downstream cone.
"""

from __future__ import annotations

import math
import subprocess
from typing import TYPE_CHECKING, TypedDict

if TYPE_CHECKING:
    import pathlib

PROJECTS = (
    *(f"{shape}-{n}" for shape in ("chain", "fan", "diamond") for n in (10, 100, 1000)),
    "multi",
)

_FAMILIES = 3
_TASKS = 4
_TASK_STAGES = 5
_PREP_STAGES = 5


class Scope(TypedDict):
    """What one `pivot repro` builds, and the files its touch and edit scenarios change."""

    name: str
    cwd: str
    args: list[str]
    touch: str
    edit_file: str
    edit_function: str


class ProjectSpec(TypedDict):
    name: str
    scopes: list[Scope]


# (function name, parameter name -> annotation, call arguments)
type _Stage = tuple[str, dict[str, str], list[str]]


def _fn(i: int) -> str:
    return f"s{i:05d}"


def _graph(shape: str, n: int) -> tuple[list[list[int]], dict[int, str], int, str, str]:
    """Return (deps per stage, raw input per stage, fan-in stage or -1, touch input, edit stage)."""
    deps = [list[int]() for _ in range(n)]
    raw = dict[int, str]()
    if shape == "chain":
        raw[0] = "in_00000"
        for i in range(1, n):
            deps[i] = [i - 1]
        return deps, raw, -1, "in_00000", _fn(n - 1)
    if shape == "fan":
        raw[0] = "in_src"
        for i in range(1, n - 1):
            deps[i] = [0]
            raw[i] = f"in_{i:05d}"
        deps[n - 1] = list(range(1, n - 1))
        return deps, raw, n - 1, "in_00001", _fn(1)
    if shape == "diamond":
        w = math.ceil(math.sqrt(n))
        for i in range(n):
            k, j = divmod(i, w)
            if k == 0:
                raw[i] = f"in_{i:05d}"
            else:
                deps[i] = sorted({(k - 1) * w + j, (k - 1) * w + (j + 1) % w})
        return deps, raw, -1, "in_00000", _fn(n - 1)
    raise ValueError(f"unknown shape {shape!r}")


def _write_inputs(root: pathlib.Path, names: list[str]) -> None:
    raw_dir = root / "data" / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    for name in names:
        (raw_dir / f"{name}.yaml").write_text(f"name: {name}\nv: 0\n")


def _write_pipeline(
    path: pathlib.Path,
    pipeline: str,
    stages: list[_Stage],
    *,
    imports: tuple[str, ...] = (),
    exports: tuple[tuple[str, str], ...] = (),
) -> None:
    lines = ["# Generated by benchmarks/gen.py.", "from __future__ import annotations", ""]
    lines += ["import zlib", "", "from pivot import Pipeline, stage", *imports, "", ""]
    for fn, params, _ in stages:
        signature = ", ".join(f"{name}: {annotation}" for name, annotation in params.items())
        folded = ", ".join(params)
        lines += [
            "@stage",
            f"def {fn}({signature}) -> dict:",
            f'    return {{"f": "{fn}", "h": zlib.crc32(repr(({folded},)).encode())}}',
            "",
            "",
        ]
    lines.append(f'with Pipeline("{pipeline}") as pipeline:')
    lines += [f"    h_{fn} = {fn}({', '.join(args)})" for fn, _, args in stages]
    lines += [f"    {name} = h_{fn}" for name, fn in exports]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def _input(name: str) -> str:
    return f'pipeline.input("{name}.yaml")'


def _write_shape(shape: str, n: int, root: pathlib.Path) -> list[Scope]:
    deps, raw, fan_in, touch, edit = _graph(shape, n)
    stages = list[_Stage]()
    for i in range(n):
        if i == fan_in:
            handles = ", ".join(f"h_{_fn(d)}" for d in deps[i])
            stages.append((_fn(i), {"xs": "list[dict]"}, [f"[{handles}]"]))
            continue
        args = [f"h_{_fn(d)}" for d in deps[i]]
        if i in raw:
            args.append(_input(raw[i]))
        stages.append((_fn(i), {f"a{k}": "dict" for k in range(len(args))}, args))
    _write_inputs(root, sorted(set(raw.values())))
    _write_pipeline(root / "pipeline.py", "bench", stages)
    return [
        Scope(
            name="pipeline",
            cwd=".",
            args=[],
            touch=f"data/raw/{touch}.yaml",
            edit_file="pipeline.py",
            edit_function=edit,
        )
    ]


def _chain(prefix: str, first_args: list[str], length: int) -> list[_Stage]:
    stages = [(f"{prefix}00", {f"a{k}": "dict" for k in range(len(first_args))}, first_args)]
    for i in range(1, length):
        stages.append((f"{prefix}{i:02d}", {"a0": "dict"}, [f"h_{prefix}{i - 1:02d}"]))
    return stages


def _write_multi(root: pathlib.Path) -> list[Scope]:
    inputs = ["prep_in"]
    prep = _chain("s", [_input("prep_in")], _PREP_STAGES)
    last = f"s{_PREP_STAGES - 1:02d}"
    _write_pipeline(root / "prep" / "pipeline.py", "prep", prep, exports=(("shared", last),))
    for f in range(_FAMILIES):
        family = f"fam_{f:02d}"
        inputs.append(f"{family}_b")
        stages: list[_Stage] = [
            ("b", {"a0": "dict", "a1": "dict"}, ["shared", _input(f"{family}_b")])
        ]
        for t in range(_TASKS):
            inputs.append(f"{family}_t{t:02d}")
            first = ["h_b", _input(f"{family}_t{t:02d}")]
            stages += _chain(f"t{t:02d}_s", first, _TASK_STAGES)
        imports = ("from prep.pipeline import shared",)
        _write_pipeline(root / family / "pipeline.py", family, stages, imports=imports)
    _write_inputs(root, inputs)
    task = f"t00_s{_TASK_STAGES - 1:02d}"
    common = {
        "cwd": "fam_00",
        "touch": "data/raw/fam_00_t00.yaml",
        "edit_file": "fam_00/pipeline.py",
        "edit_function": task,
    }
    return [
        # One task with its upstream stages: its own chain, fam_00/b and all of prep.
        Scope(name="task", args=[f"fam_00/{task}"], **common),
        # One pipeline with its upstream stages: fam_00 and all of prep, not fam_01 or fam_02.
        Scope(name="pipeline", args=[], **common),
    ]


def write_project(name: str, root: pathlib.Path, pivot: pathlib.Path) -> ProjectSpec:
    """Create project `name` at `root` (which must not exist), initialised with `pivot init`."""
    if name not in PROJECTS:
        raise ValueError(f"unknown project {name!r}; choose from {', '.join(PROJECTS)}")
    root.mkdir(parents=True)
    subprocess.run([str(pivot), "init"], cwd=root, check=True, stdout=subprocess.DEVNULL)
    if name == "multi":
        scopes = _write_multi(root)
    else:
        shape, n = name.rsplit("-", 1)
        scopes = _write_shape(shape, int(n), root)
    return ProjectSpec(name=name, scopes=scopes)
